namespace NoMorePaper.Architecture.Tests;

/// <summary>The C# sources and folders of the shipped projects under src/ (no build output, no generated code).</summary>
internal static class SourceFiles
{
    private static readonly Lazy<string> s_srcRoot = new(() => Path.Combine(RepositoryRoot(), "src"));
    private static readonly Lazy<IReadOnlyList<SourceFile>> s_production = new(Load);

    public static IReadOnlyList<SourceFile> Production() => s_production.Value;

    public static IEnumerable<string> ProductionFolders() =>
        Directory.EnumerateDirectories(s_srcRoot.Value, "*", SearchOption.AllDirectories)
            .Where(path => !IsBuildOutput(path))
            .Select(path => Path.GetRelativePath(s_srcRoot.Value, path));

    private static List<SourceFile> Load() =>
        Directory.EnumerateFiles(s_srcRoot.Value, "*.cs", SearchOption.AllDirectories)
            .Where(path => !IsBuildOutput(path) && !IsGenerated(path))
            .Select(path => new SourceFile(path, ProjectOf(path), File.ReadAllText(path)))
            .ToList();

    private static string RepositoryRoot()
    {
        var folder = new DirectoryInfo(AppContext.BaseDirectory);
        while (folder is not null && !File.Exists(Path.Combine(folder.FullName, "NoMorePaper.slnx")))
        {
            folder = folder.Parent;
        }

        return folder?.FullName ?? throw new InvalidOperationException("NoMorePaper.slnx not found above " + AppContext.BaseDirectory);
    }

    private static string ProjectOf(string path) =>
        Path.GetRelativePath(s_srcRoot.Value, path).Split(Path.DirectorySeparatorChar)[0];

    private static bool IsBuildOutput(string path)
    {
        var segments = path.Split(Path.DirectorySeparatorChar);
        return segments.Contains("bin") || segments.Contains("obj");
    }

    // EF Core migrations are generated by `dotnet ef` and exempt like other generated code.
    private static bool IsGenerated(string path) =>
        path.EndsWith(".g.cs", StringComparison.Ordinal)
        || path.EndsWith(".Designer.cs", StringComparison.Ordinal)
        || path.Split(Path.DirectorySeparatorChar).Contains("Migrations");
}
